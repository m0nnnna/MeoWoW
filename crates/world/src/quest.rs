/// Which quest a questgiver is showing, out of
/// `SMSG_QUESTGIVER_QUEST_DETAILS`.
///
/// **Deliberately reads the first twenty bytes and nothing else.** Everything
/// after them is the quest's title, text, objectives and rewards -- the same
/// content `SMSG_QUEST_QUERY_RESPONSE` carries, in a different layout. Parsing
/// it a second time would give this client two independently-derived copies of
/// the same strings, and two copies drift: the rule that says derive from the
/// same source when two things must agree exactly. The query's answer is
/// already cached per realm and already verified against 9,464 quests, so this
/// packet is used for the one thing the query cannot say -- *which* quest the
/// NPC just put on screen.
///
/// The layout of the part that is read was confirmed on two captures with
/// different quests and different NPCs: quest 333 from Harlan Bagley and quest
/// 783 from Deputy Willem, both with the id at offset 16.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct QuestgiverDetails {
    pub npc: u64,
    pub quest: u32,
}

/// Parses the head of `SMSG_QUESTGIVER_QUEST_DETAILS`.
pub fn parse_questgiver_details(body: &[u8]) -> Result<QuestgiverDetails, Error> {
    let mut r = Reader::new(body, "SMSG_QUESTGIVER_QUEST_DETAILS");
    let npc = r.u64()?;
    // Zero on both captures. The server sends a second guid here -- the
    // *originator* of the quest, which differs from the questgiver only for
    // quests started by an item -- and naming it on two zeroes would be
    // transcribing rather than measuring.
    let _unconfirmed = r.u64()?;
    let quest = r.u32()?;
    // **Taken rather than ignored.** A parser that left a tail unread would
    // still pass `finish`, and would be making no claim at all about how much
    // of the packet it understood. See `Reader::rest`.
    let _ = r.rest();
    r.finish()?;
    Ok(QuestgiverDetails { npc, quest })
}

/// What mark belongs over an NPC's head.
///
/// **Every value here was produced by a state this project created, one change
/// at a time, and nothing else is named.** The wire carries a single byte and
/// the temptation is to write the whole enum down from memory -- which is the
/// urge that produced `CHAT_MSG_SAY = 0x00` and cost a day. So: a character
/// was created from nothing, and the same four questgivers were asked about
/// after each change to its quest log.
///
/// | byte | how it was produced |
/// |---|---|
/// | 0 | an innkeeper with no quests, and a questgiver whose quests are gated behind one not yet done |
/// | 2 | the same available quest, asked by a character levelled to 26 |
/// | 5 | quest 7 in the log with none of its eight kobolds killed, asked at its ender |
/// | 8 | quest 783 on offer to a fresh level-one human |
/// | 10 | quest 783 in the log and finished, asked at its ender |
///
/// Anything else reads as [`QuestgiverMark::Unknown`] and draws nothing. A
/// mark this client has not seen the server produce is a guess, and a wrong
/// exclamation over an NPC sends a player somewhere for no reason.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum QuestgiverMark {
    /// Nothing to offer and nothing to hand in.
    None,
    /// A quest is on offer. The bright exclamation.
    Available,
    /// A quest is on offer, and the character has outlevelled it. The grey
    /// exclamation.
    AvailableTrivial,
    /// A quest of theirs is in the log and not finished. The grey question
    /// mark.
    Incomplete,
    /// A quest of theirs is in the log and finished. The bright question mark.
    Complete,
    /// A value the server sent that this client has never produced
    /// deliberately, so it has no name and draws nothing.
    Unknown(u8),
}

impl QuestgiverMark {
    /// Reads the byte the server sends. See the type's own table.
    pub fn from_status(raw: u8) -> Self {
        match raw {
            0 => Self::None,
            2 => Self::AvailableTrivial,
            5 => Self::Incomplete,
            8 => Self::Available,
            10 => Self::Complete,
            other => Self::Unknown(other),
        }
    }

    /// Whether anything should be drawn over the NPC at all.
    pub fn is_drawn(self) -> bool {
        matches!(
            self,
            Self::Available | Self::AvailableTrivial | Self::Incomplete | Self::Complete
        )
    }
}

/// One NPC's mark, in answer to `CMSG_QUESTGIVER_STATUS_QUERY`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct QuestgiverStatus {
    pub npc: u64,
    pub mark: QuestgiverMark,
}

/// Parses `SMSG_QUESTGIVER_STATUS`: a guid and one byte.
///
/// **Nine bytes, confirmed by the guid coming back.** Nothing acknowledges an
/// outgoing opcode, so the proof that `CMSG_QUESTGIVER_STATUS_QUERY` is the
/// right number is that the reply names the exact NPC it was asked about --
/// twenty-nine of them in one run, each matching its own request.
pub fn parse_questgiver_status(body: &[u8]) -> Result<QuestgiverStatus, Error> {
    let mut r = Reader::new(body, "SMSG_QUESTGIVER_STATUS");
    let npc = r.u64()?;
    let status = r.u8()?;
    r.finish()?;
    Ok(QuestgiverStatus {
        npc,
        mark: QuestgiverMark::from_status(status),
    })
}

/// One marker area for a quest objective -- a polygon on the world map.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QuestPoi {
    /// The marker's index within this quest's own set.
    pub id: u32,
    /// Which objective this marks, or `None` for a marker belonging to the
    /// quest as a whole rather than to one of its objectives.
    ///
    /// **Signed on the wire and `-1` is the common case** -- all three
    /// single-objective quests captured carry it. Reading it unsigned would
    /// report objective 4,294,967,295 and quietly attach every marker to an
    /// objective that does not exist.
    pub objective_index: Option<u32>,
    pub map_id: u32,
    /// A row in `WorldMapArea.dbc`, **not** `AreaTable.dbc**. Named after the
    /// server's own column (`quest_poi.WorldMapAreaId`) rather than after a
    /// guess: the two tables are different and both are keyed by small
    /// integers, so a wrong reading would resolve to a plausible wrong place.
    pub world_map_area_id: u32,
    pub floor_id: u32,
    /// The polygon. One point is a pin; several outline a region.
    ///
    /// **Coordinates are world coordinates and are signed**, which the capture
    /// makes unambiguous: Northshire sits at negative x and negative y, and
    /// every point captured there is negative in both.
    pub points: Vec<(i32, i32)>,
    /// Two fields nothing has explained. Zero and one on every marker
    /// captured, and **deliberately unnamed**: the server's own struct calls
    /// them `Unk3` and `Unk4`, so there is nothing to transcribe even if
    /// transcribing were wanted.
    pub unknown: (u32, u32),
}

/// Every marker the server returned for one quest.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QuestPoiSet {
    pub quest_id: u32,
    /// **Empty is a real and common answer**, not a failure. The server sends
    /// a zero count for a quest it has no markers for *and* for a quest that
    /// is not in the player's log -- the two are indistinguishable here, which
    /// is worth knowing before reading an empty set as "this quest has no
    /// objectives on the map".
    pub markers: Vec<QuestPoi>,
}

/// Parses `SMSG_QUEST_POI_QUERY_RESPONSE`.
///
/// Read through a cursor that must end exactly at the end of the body. This
/// packet nests three levels of counted array, so a single miscount does not
/// shift one value -- it desynchronises everything after it, and a coordinate
/// read from the wrong offset is still a plausible-looking number.
pub fn parse_quest_poi(body: &[u8]) -> Result<Vec<QuestPoiSet>, Error> {
    let mut r = Reader::new(body, "SMSG_QUEST_POI_QUERY_RESPONSE");

    let quests = r.u32()?;
    let mut sets = Vec::with_capacity(quests as usize);
    for _ in 0..quests {
        let quest_id = r.u32()?;
        let marker_count = r.u32()?;
        let mut markers = Vec::with_capacity(marker_count as usize);
        for _ in 0..marker_count {
            let id = r.u32()?;
            // Signed: -1 means "not tied to one objective". See the field.
            let objective_index = match r.u32()? as i32 {
                negative if negative < 0 => None,
                index => Some(index as u32),
            };
            let map_id = r.u32()?;
            let world_map_area_id = r.u32()?;
            let floor_id = r.u32()?;
            let unknown = (r.u32()?, r.u32()?);
            let point_count = r.u32()?;
            let mut points = Vec::with_capacity(point_count as usize);
            for _ in 0..point_count {
                points.push((r.u32()? as i32, r.u32()? as i32));
            }
            markers.push(QuestPoi {
                id,
                objective_index,
                map_id,
                world_map_area_id,
                floor_id,
                points,
                unknown,
            });
        }
        sets.push(QuestPoiSet { quest_id, markers });
    }

    r.finish()?;
    Ok(sets)
}

