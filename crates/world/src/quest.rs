//! Quests, and where their objectives are on the map.
//!
//! **This module is why this client does not ship anybody's quest database.**
//! WotLK shipped its own quest tracker, so the server already stores the map
//! markers and hands them over on request -- 8,953 of 9,464 quests carry them
//! on the development realm. Asking is strictly better than shipping a copy:
//! the answer cannot drift as content is patched, and it is *correct* on a
//! private realm with custom quests, where a shipped database is simply wrong.
//!
//! **The one constraint shapes everything built on top.** The server answers
//! only for quests **in the player's own log**, and takes at most 25 ids per
//! request. So this covers "where do I go for the quest I am on" completely,
//! and says nothing whatever about a quest not yet accepted -- which is a
//! different feature needing a different source.
//!
//! Confirmed field by field against the server's own `quest_poi` and
//! `quest_poi_points` tables, which the client is never sent:
//!
//! | quest | on the wire | in the database |
//! |---|---|---|
//! | 85 | area 30, point (-9924, 38) | area 30, (-9924, 38) |
//! | 106 | area 39, point (-9930, 500) | area 39, (-9930, 500) |
//! | 783 | area 30, point (-8903, -163) | area 30, (-8903, -163) |
//! | 16 | 15 marker areas | 15 |
//!
//! And a sanity check no table could give: quest 783's marker is *Speak with
//! Marshal McBride*, and it arrived at (-8903, -163) while the character
//! standing in Northshire was at (-8928, -187). The numbers are real world
//! coordinates in the right place, not merely well-formed.

use crate::protocol::{Error, Reader};

/// How many reward items a quest hands over unconditionally.
const REWARD_ITEMS: usize = 4;
/// How many rewards a quest can offer a *choice* between.
const REWARD_CHOICES: usize = 6;
/// How many factions one quest can move standing with.
const REWARD_FACTIONS: usize = 5;
/// How many creature-or-object objectives a quest can carry.
const OBJECTIVES: usize = 4;
/// How many item objectives a quest can carry. **Six, not four** -- the two
/// counts differ, and a reader assuming they match walks off the end of one
/// array into the start of the next without erroring.
const ITEM_OBJECTIVES: usize = 6;

/// What one objective wants killed, used or spoken to.
///
/// **A creature id and a game object id are the same small number, and the
/// wire distinguishes them by setting the top bit.** Reading the field as a
/// plain `u32` gives 2,147,485,369 for a game object, which is not a plausible
/// creature and would at least fail loudly -- but reading it as `i32` and
/// negating, which is what the server's own table stores, gives a *valid*
/// creature id pointing at the wrong thing entirely. So the discrimination is
/// made once, here, and callers get a type that cannot be confused.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ObjectiveTarget {
    /// A row in `creature_template`: kill it, or speak to it.
    Creature(u32),
    /// A row in `gameobject_template`: use it, or click it.
    GameObject(u32),
}

impl ObjectiveTarget {
    /// The bit the server sets to mean "this id is a game object".
    const GAMEOBJECT: u32 = 0x8000_0000;

    fn from_wire(raw: u32) -> Self {
        if raw & Self::GAMEOBJECT != 0 {
            Self::GameObject(raw & !Self::GAMEOBJECT)
        } else {
            Self::Creature(raw)
        }
    }
}

/// One "kill N of these" or "use N of those" objective.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QuestObjective {
    /// Which of the wire's four objective slots this came from, `0..4`.
    ///
    /// **Kept because the list is pruned and the progress counter is not.**
    /// The player's quest-log entry holds one counter per *wire* slot, so a
    /// quest whose only objective sits in slot 2 has its kills counted in
    /// counter 2 -- and a client that used the position in this trimmed list
    /// would read counter 0, which is some other objective's progress or a
    /// permanent zero. Nothing about either number looks wrong on screen.
    pub slot: u8,
    /// What to kill or use, and **`None` is a real slot rather than an empty
    /// one.** Quest 28 names no creature at all and still carries an item
    /// drop, so a reader that treats "target zero" as "no objective here"
    /// throws that drop away in silence. The two are separated instead: a
    /// slot with neither a target nor a drop is dropped, and one with only a
    /// drop survives with nothing to kill.
    pub target: Option<ObjectiveTarget>,
    pub count: u32,
    /// An item this objective's target drops *for the quest only*, which the
    /// quest log shows as a sub-line. Zero when the objective drops nothing.
    pub item_drop: u32,
    /// The text shown beside this objective when the server overrides the
    /// generated "Kill 7 Tidehunters" line. Usually empty.
    pub text: String,
}

/// One "bring N of this item" objective.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct QuestItemObjective {
    pub item: u32,
    pub count: u32,
}

/// One item a quest hands over, or offers a choice between.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct QuestRewardItem {
    pub item: u32,
    pub count: u32,
}

/// Everything the server will say about one quest, in answer to
/// [`CMSG_QUEST_QUERY`](crate::ClientOpcode::QuestQuery).
///
/// **This is the packet the whole quest feature rests on**, because unlike a
/// questgiver's scroll it answers for *any* quest id, with no NPC in front of
/// the player and no entry in the player's log. A tracker has to describe
/// quests the player is not standing next to, and a map has to label a pin for
/// a quest not yet taken; both need exactly this and nothing else would do.
///
/// Empty arrays are pruned rather than carried as zeroes: a quest with one
/// objective has one, not four with three blanks. Zero is not a creature, an
/// item or a faction, so nothing is lost, and every consumer would otherwise
/// have to re-filter.
#[derive(Debug, Clone, PartialEq)]
pub struct QuestInfo {
    pub id: u32,
    /// `0` means the quest completes itself with no objectives to do. The
    /// server's own comment calls it the quest *method*.
    pub method: u32,
    /// The level the quest is balanced for, which is what a tracker colours
    /// by. **Signed on the wire**: `-1` marks a quest that scales to the
    /// player rather than one at level 4,294,967,295.
    pub level: i32,
    pub min_level: u32,
    /// Which heading the quest sorts under in the log. Positive values are
    /// zones; negative ones are a row in `QuestSort.dbc` such as a profession.
    pub sort: i32,
    /// `QuestInfoID` -- daily, group, raid, and so on.
    pub info_type: u32,
    pub suggested_players: u32,
    /// The next quest in the chain, which a client may request from the same
    /// NPC without being offered it. Zero when the chain ends.
    ///
    /// Confirmed by effect rather than by the table alone: quest 783 carries
    /// `7`, and handing 783 in put exactly quest 7 into the log.
    pub next_quest: u32,
    /// A row in `QuestXP.dbc` rather than an amount of experience. Named for
    /// what it is: reporting it as XP would put a number nobody can check on a
    /// tooltip, which this project treats as worse than a blank.
    pub xp_difficulty: u32,
    /// Copper paid on completion below max level. **Zero here is ambiguous by
    /// design on the server's side**: a quest flagged to hide its rewards
    /// sends `0` rather than the real figure, so a client showing "no money"
    /// may be showing a deliberate blank.
    pub money: u32,
    /// Copper paid instead once the character is at the level cap. Derived by
    /// the server from the quest's level and **not** a column of
    /// `quest_template` -- checked against the realm's database, where the
    /// nearest-named column is zero on every quest captured while this field
    /// is not.
    pub money_at_max_level: u32,
    pub reward_spell: u32,
    /// The spell actually cast on completion, as opposed to the one whose icon
    /// is shown. Signed on the wire.
    pub reward_spell_cast: i32,
    pub reward_honor: u32,
    pub reward_honor_multiplier: f32,
    /// An item the quest *gives you to start with*, such as a letter to
    /// deliver. Zero for most quests.
    pub start_item: u32,
    /// **Only the low sixteen bits reach the client.** The server sends
    /// `Flags & 0xFFFF`, which silently drops `QUEST_FLAGS_AUTO_ACCEPT`
    /// (`0x80000`) -- so a quest that the server will take on the player's
    /// behalf the moment its scroll is requested looks, in this packet,
    /// exactly like one that will not. Measured first: quest 783 arrives here
    /// as `8` where the realm's own table says `524296`. Do not use this field
    /// to predict whether an accept is needed.
    pub flags: u32,
    pub reward_title: u32,
    pub required_player_kills: u32,
    pub reward_talents: u32,
    pub reward_arena_points: u32,
    pub reward_items: Vec<QuestRewardItem>,
    pub reward_choices: Vec<QuestRewardItem>,
    /// Faction id paired with a *row in `QuestFactionReward.dbc`*, not an
    /// amount of reputation. Named `value` rather than `reputation` for that
    /// reason.
    pub reward_factions: Vec<(u32, i32)>,
    /// A single point of interest carried inline, distinct from the polygons
    /// [`parse_quest_poi`] returns. Present on a minority of quests; `None`
    /// when the map id and both coordinates are zero.
    pub point: Option<QuestPoint>,
    pub title: String,
    /// The one-line "what to do" shown under the title in the log.
    pub objectives_text: String,
    /// The questgiver's full spoken text.
    pub details: String,
    pub area_description: String,
    /// Shown once every objective is done.
    pub completed_text: String,
    pub objectives: Vec<QuestObjective>,
    pub item_objectives: Vec<QuestItemObjective>,
}

/// The inline point of interest some quests carry.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct QuestPoint {
    pub map: u32,
    pub x: f32,
    pub y: f32,
    /// The server calls this `PointOpt` and nothing has explained it. Left
    /// unnamed rather than guessed.
    pub option: u32,
}

/// Parses `SMSG_QUEST_QUERY_RESPONSE`.
///
/// **A 260-byte fixed head, five strings, then two more arrays**, and the
/// arrays after the strings are why this cannot be read by offset: nothing
/// past byte 260 sits at a fixed place. Read through a cursor that must end
/// exactly at the end of the body.
///
/// The layout was measured before it was confirmed, on eight quests chosen so
/// that every array count differs between them -- one with four creature
/// objectives, one with four item objectives, one with five reward choices,
/// one with four reward items, and one with nothing at all. A quest with
/// empty arrays parses perfectly under a reading that has the two objective
/// blocks the wrong way round, which is why the sample had to disagree with
/// itself.
pub fn parse_quest_query(body: &[u8]) -> Result<QuestInfo, Error> {
    let mut r = Reader::new(body, "SMSG_QUEST_QUERY_RESPONSE");

    let id = r.u32()?;
    let method = r.u32()?;
    let level = r.u32()? as i32;
    let min_level = r.u32()?;
    let sort = r.u32()? as i32;
    let info_type = r.u32()?;
    let suggested_players = r.u32()?;
    // Two faction *requirements* -- a standing the player must already have
    // before the quest is offered. Zero on every quest captured, and skipped
    // rather than named: a field nothing has exercised is a field whose
    // meaning is a guess.
    r.skip(4 * 4)?;
    let next_quest = r.u32()?;
    let xp_difficulty = r.u32()?;
    let money = r.u32()?;
    let money_at_max_level = r.u32()?;
    let reward_spell = r.u32()?;
    let reward_spell_cast = r.u32()? as i32;
    let reward_honor = r.u32()?;
    let reward_honor_multiplier = r.f32()?;
    let start_item = r.u32()?;
    let flags = r.u32()?;
    let reward_title = r.u32()?;
    let required_player_kills = r.u32()?;
    let reward_talents = r.u32()?;
    let reward_arena_points = r.u32()?;
    // The server's own comment calls this a "review rep show mask" and sends a
    // literal zero for it. Nothing to name.
    r.skip(4)?;

    let mut reward_items = Vec::new();
    for _ in 0..REWARD_ITEMS {
        let item = r.u32()?;
        let count = r.u32()?;
        if item != 0 {
            reward_items.push(QuestRewardItem { item, count });
        }
    }
    let mut reward_choices = Vec::new();
    for _ in 0..REWARD_CHOICES {
        let item = r.u32()?;
        let count = r.u32()?;
        if item != 0 {
            reward_choices.push(QuestRewardItem { item, count });
        }
    }

    // **Three parallel arrays, not five triples.** All five ids come first,
    // then all five values, then five overrides -- so a reader that pairs them
    // as it goes reads faction 2's id as faction 1's value, and both are small
    // integers that look fine.
    let mut faction_ids = [0u32; REWARD_FACTIONS];
    for slot in faction_ids.iter_mut() {
        *slot = r.u32()?;
    }
    let mut faction_values = [0i32; REWARD_FACTIONS];
    for slot in faction_values.iter_mut() {
        *slot = r.u32()? as i32;
    }
    // The override array is zero on every quest captured and the server's own
    // comment for it is `unk (0)`.
    r.skip(4 * REWARD_FACTIONS)?;
    let reward_factions = faction_ids
        .iter()
        .zip(faction_values.iter())
        .filter(|(id, _)| **id != 0)
        .map(|(id, value)| (*id, *value))
        .collect();

    let point_map = r.u32()?;
    let point_x = r.f32()?;
    let point_y = r.f32()?;
    let point_option = r.u32()?;
    // All-zero is how the great majority of quests say "no inline point", and
    // reporting that as a marker at the map's origin would put a pin in the
    // sea. `option` is deliberately not part of the test: it is the one field
    // here nothing has explained.
    let point = (point_map != 0 || point_x != 0.0 || point_y != 0.0).then_some(QuestPoint {
        map: point_map,
        x: point_x,
        y: point_y,
        option: point_option,
    });

    let title = r.cstring()?;
    let objectives_text = r.cstring()?;
    let details = r.cstring()?;
    let area_description = r.cstring()?;
    let completed_text = r.cstring()?;

    // **The objective texts do not travel with their objectives.** All four
    // numeric groups come first and all four strings come after the item
    // objectives, so they are read separately and zipped back together here
    // rather than in the loop -- which is also why a quest whose objectives
    // are all empty cannot distinguish this reading from several wrong ones.
    let mut targets = Vec::with_capacity(OBJECTIVES);
    for _ in 0..OBJECTIVES {
        let raw = r.u32()?;
        let target = (raw != 0).then(|| ObjectiveTarget::from_wire(raw));
        let count = r.u32()?;
        let item_drop = r.u32()?;
        // The server writes a literal zero here where its own table has an
        // item-drop *quantity*, so the quantity genuinely does not travel.
        r.skip(4)?;
        targets.push((target, count, item_drop));
    }

    let mut item_objectives = Vec::new();
    for _ in 0..ITEM_OBJECTIVES {
        let item = r.u32()?;
        let count = r.u32()?;
        if item != 0 {
            item_objectives.push(QuestItemObjective { item, count });
        }
    }

    let mut objectives = Vec::new();
    for (slot, (target, count, item_drop)) in targets.into_iter().enumerate() {
        let text = r.cstring()?;
        // **The string is read for every slot, kept only for some.** All four
        // are on the wire whether the slot is used or not, so reading only the
        // used ones desynchronises everything after them -- which here is the
        // end of the packet, so it would surface as a spurious trailing-bytes
        // error rather than as wrong data. Read first, filter second.
        if target.is_some() || item_drop != 0 {
            objectives.push(QuestObjective {
                slot: slot as u8,
                target,
                count,
                item_drop,
                text,
            });
        }
    }

    r.finish()?;
    Ok(QuestInfo {
        id,
        method,
        level,
        min_level,
        sort,
        info_type,
        suggested_players,
        next_quest,
        xp_difficulty,
        money,
        money_at_max_level,
        reward_spell,
        reward_spell_cast,
        reward_honor,
        reward_honor_multiplier,
        start_item,
        flags,
        reward_title,
        required_player_kills,
        reward_talents,
        reward_arena_points,
        reward_items,
        reward_choices,
        reward_factions,
        point,
        title,
        objectives_text,
        details,
        area_description,
        completed_text,
        objectives,
        item_objectives,
    })
}

#[cfg(test)]
mod details_tests {
    use super::*;

    /// Both captures, head only: quest 783 from Deputy Willem and quest 333
    /// from Harlan Bagley. **Two, because one would not distinguish offset 16
    /// from any other place a small integer happens to sit** -- and these two
    /// disagree in both the guid and the quest.
    #[test]
    fn the_quest_id_sits_at_the_measured_offset() {
        let willem = [
            0x8f, 0x2f, 0x01, 0x37, 0x03, 0x00, 0x30, 0xf1, // npc guid
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // unconfirmed, zero
            0x0f, 0x03, 0x00, 0x00, // quest 783
            b'A', 0x00, // the title begins; the rest is taken, not read
        ];
        let parsed = parse_questgiver_details(&willem).unwrap();
        assert_eq!(parsed.quest, 783);
        assert_eq!(parsed.npc, 0xf130_0003_3701_2f8f);

        let harlan = [
            0x0b, 0x30, 0x01, 0x93, 0x05, 0x00, 0x30, 0xf1, //
            0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, //
            0x4d, 0x01, 0x00, 0x00, // quest 333
        ];
        let parsed = parse_questgiver_details(&harlan).unwrap();
        assert_eq!(parsed.quest, 333);
        assert_ne!(parsed.npc, 0xf130_0003_3701_2f8f, "a different NPC");
    }

    /// A body too short to hold the head is an error rather than a quest id
    /// read out of whatever followed.
    #[test]
    fn a_short_body_is_an_error() {
        assert!(parse_questgiver_details(&[0u8; 19]).is_err());
    }
}

